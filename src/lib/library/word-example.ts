/**
 * How hard this sentence is, as the rank of the hardest word in it.
 *
 * THE TARGET WORD IS EXCLUDED. It is in `v` for every candidate by
 * construction, so including it would make it the maximum on every candidate
 * for any word rarer than the sentences around it — and then every candidate
 * ties and the ranking collapses to "shortest". The owner asked for sentences
 * whose vocabulary is common; on 沿う that means the OTHER words, because 沿う
 * itself is not negotiable. So the max is taken over the rest.
 */
export function hardestRank(ex: Example, target: string, rankOf: RankOf): number {
  let worst = 0;
  for (const lemma of ex.v) {
    if (lemma === target) continue;
    worst = Math.max(worst, rankOf(lemma) ?? UNRANKED);
  }
  return worst;
}

/**
 * The one sentence to show for `target`, or null if there is none.
 *
 * Ordered by hardest word (commonest wins), then by whether the sentence
 * spells `target` LITERALLY (SAK-97 — a sentence that shows the word's own
 * dictionary form gets a highlight span for free, one that only shows a
 * conjugated form needs scripts/ingest/sentence_readings.py's tokenizer to
 * find it; independent of and secondary to vocabulary difficulty, but worth
 * preferring over a marginally shorter sentence), then by token count
 * (shorter wins), then by Tatoeba id. The last key is what makes this a total
 * order: two sentences can agree on all of the above, and a pick that depends
 * on corpus iteration order is a pick that can move when the corpus is
 * rebuilt.
 */
export function chooseExample(
  candidates: readonly Example[],
  target: string,
  rankOf: RankOf,
): Example | null {
  let best: Example | null = null;
  let bestScore = Infinity;
  const banned = WRONG_SENSE_EXAMPLES[target];
  for (const ex of candidates) {
    // Never pick a sentence whose translation teaches the wrong sense of the
    // very word it is keyed to (task-20 item 3). A word all of whose candidates
    // are banned gets no example, which is better than a false one.
    if (banned?.includes(ex.id)) continue;
    const score = hardestRank(ex, target, rankOf);
    if (best === null || score < bestScore) {
      best = ex;
      bestScore = score;
      continue;
    }
    if (score > bestScore) continue;
    const exLiteral = ex.jp.includes(target);
    const bestLiteral = best.jp.includes(target);
    if (exLiteral !== bestLiteral) {
      if (exLiteral) best = ex;
      continue;
    }
    if (ex.n !== best.n) {
      if (ex.n < best.n) best = ex;
      continue;
    }
    if (ex.id < best.id) best = ex;
  }
  return best;
}

/**
 * The candidate pool cut from the WHOLE Tatoeba export for the words the
 * grammar corpus never reached (SAK-461), as
 * src/data/generated/word-example-candidates.json holds it.
 *
 * Tuple-packed and sentence-deduplicated on disk, because a sentence is a
 * candidate for several words at once and the file is committed: `sentences`
 * holds each one once as [id, jp, en, tokenCount, contentLemmas], and `byWord`
 * points a written form at its own rows by index.
 */
export interface CandidateFile {
  readonly sentences: readonly (readonly [number, string, string, number, readonly string[]])[];
  readonly byWord: Readonly<Record<string, readonly number[]>>;
}

/**
 * That file, unpacked into the same `Example` shape chooseExample already
 * takes, so the wider pool and the corpus pool are the same kind of thing to
 * the chooser.
 *
 * `p` and `sp` are empty: these rows are never added to CORPUS or AUTHORED and
 * never enter grammar-pattern drilling, exactly like EXTRA_EXAMPLES's rows.
 * They exist only as chooseExample candidates for the word named by the key.
 */
export function candidatesByWord(file: CandidateFile): Map<string, Example[]> {
  const map = new Map<string, Example[]>();
  for (const [keb, slots] of Object.entries(file.byWord)) {
    map.set(
      keb,
      slots.map((slot) => {
        const [id, jp, en, n, v] = file.sentences[slot]!;
        return { id, jp, en, n, v, p: [], sp: {} };
      }),
    );
  }
  return map;
}

/** Every sentence containing each written form, keyed by that form. Built once,
 * at build time, over the whole corpus. */
export function indexByWord(corpus: readonly Example[]): Map<string, Example[]> {
  const map = new Map<string, Example[]>();
  for (const ex of corpus) {
    for (const lemma of ex.v) {
      const list = map.get(lemma);
      if (list) list.push(ex);
      else map.set(lemma, [ex]);
    }
  }
  return map;
}
